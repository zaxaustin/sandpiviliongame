/* ================================================================
   [BUILD THE DEMO SHELF] — the one-press armful for the web build.

   ⚠ THIS DOES NOT REVERSE THE EMPTY-SHELF DECISION, and the difference
   matters. `SEED_LIBRARY` is [] and stays [] — nothing ships ON the
   shelves, in any build. What this makes is a bundle that a person can
   choose to load, with one press, on a deployment whose whole job is to
   be looked at by someone who is not going to install anything.

   CLAUDE.md, 2026-08-10: "a shelf of 27 books nobody chose was doing the
   ownership argument harm." Still true. The fix is not to hide the
   Pavilion from a visitor with no books — it is that filling the shelf
   is a decision somebody makes. One press is a decision. A shelf that is
   already full when you arrive is not.

   ⚠ AND IT IS BOUNDED BY A MEASURED CEILING. In a browser every book's
   text lives in one ~5 MB localStorage key (measured: the ninth
   563 KB book throws QuotaExceededError). WEB_SAVE_CEILING is 4300 KB.
   This bundle deliberately spends well under half of it, so a visitor
   who wants to bring their OWN book still can — a demo that fills the
   room and then refuses the visitor teaches the wrong thing.

   Run:  node scripts/build-demo-shelf.mjs
   Out:  src/game/data/demo-shelf.js  (loaded by dynamic import, so it
         is its own chunk and costs nothing until the button is pressed)
   ================================================================ */
import { readFileSync, writeFileSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const KB = n => Math.round(n / 1024);

/* Every course file in the repo, read as raw Markdown and parsed by the
   app's own parseCourse() at load time — never re-emitted here, so the
   demo cannot drift from the file the steward actually wrote. */
const COURSES = [
  'courses/junior-electrical-engineer.course.md',
  'courses/theoretical-minimum.course.md',
];

/* Chosen to stand behind the two courses rather than to look impressive:
   Tesla and Faraday for the electrical path, Franklin for the idea that
   you can teach yourself a subject, and two short ones so the shelf has
   some range. All public domain, all already in library-sources/. */
const BOOKS = [
  { file: 'the-inventions-researches-and-writings-of-nikola-tesla.txt',
    title: 'The Inventions, Researches and Writings of Nikola Tesla',
    author: 'Thomas Commerford Martin', shelf: 'Science' },
  { file: 'the-chemical-history-of-a-candle.txt',
    title: 'The Chemical History of a Candle',
    author: 'Michael Faraday', shelf: 'Science' },
  { file: 'franklin-autobiography.txt',
    title: 'The Autobiography of Benjamin Franklin',
    author: 'Benjamin Franklin', shelf: 'Non-fiction' },
  { file: 'art-of-war.txt',
    title: 'The Art of War',
    author: 'Sun Tzu', shelf: 'Classics' },
  { file: 'the-diamond-sutra-chin-kang-ching-or-prajna-paramita.txt',
    title: 'The Diamond Sutra',
    author: 'translated by William Gemmell', shelf: 'Mahayana' },
];

const LICENSE = 'Public domain';
const SOURCE = 'Project Gutenberg';

const books = BOOKS.map(b => {
  const path = join(ROOT, 'library-sources', b.file);
  const text = readFileSync(path, 'utf8');
  const summary = text.slice(0, 240).replace(/\s+\S*$/, '') + (text.length > 240 ? '…' : '');
  return {
    slug: 'demo-' + b.file.replace(/\.txt$/, '').slice(0, 60),
    title: b.title, tradition: b.shelf, license: LICENSE, source_url: SOURCE,
    attribution: b.author, category: 'personal', personal: true,
    doc: { summary, sections: [], fullText: { license: LICENSE, source_url: SOURCE, text } },
  };
});

const courses = COURSES.map(f => readFileSync(join(ROOT, f), 'utf8'));

const bytes = JSON.stringify({ books, courses }).length;
const CEILING = 4300 * 1024;

/* ⚠ EXPORTED SO npm test CAN REBUILD IT AND COMPARE. A generated file that is
   committed alongside its sources is a list that must match another file, which
   is rule 4's exact shape: add a course to courses/ and the demo silently keeps
   shipping the old pair. The guard regenerates from the same inputs and diffs
   the text, so drift is impossible rather than merely unlikely. */
export function demoShelfSource(){
  return `/* GENERATED by scripts/build-demo-shelf.mjs — do not edit by hand.
   Run \`npm run demo:shelf\` after changing courses/ or the lists in that script.
   ${books.length} public-domain books + ${courses.length} real courses, ${KB(bytes)} KB.
   Loaded by dynamic import() so it is its own chunk and costs nothing
   until somebody presses the button. See the script for why this does
   NOT reverse the empty-shelf decision. */
export const DEMO_BOOKS = ${JSON.stringify(books)};
export const DEMO_COURSES = ${JSON.stringify(courses)};
export const DEMO_BYTES = ${bytes};
`;
}
export const DEMO_SHELF_PATH = join(ROOT, 'src/game/data/demo-shelf.js');
export const DEMO_SHELF_STATS = { books: books.length, courses: courses.length, bytes, ceiling: CEILING };

/* only write when run directly, never on import from the guard */
if (process.argv[1] && process.argv[1].endsWith('build-demo-shelf.mjs')) {
  if (bytes > CEILING * 0.6) {
    console.error(`\n✗ the demo shelf is ${KB(bytes)} KB, more than 60% of the ${KB(CEILING)} KB browser`
      + ` ceiling. A demo that fills the room and then refuses the visitor's own book teaches the`
      + ` wrong thing — drop a book.\n`);
    process.exit(1);
  }
  writeFileSync(DEMO_SHELF_PATH, demoShelfSource());
  console.log(`\n✓ demo shelf built — ${books.length} books, ${courses.length} courses, ${KB(bytes)} KB`
    + ` (${Math.round(bytes / CEILING * 100)}% of the browser ceiling)`);
  for (const b of books) console.log(`    ${String(KB(JSON.stringify(b).length)).padStart(5)} KB  ${b.title}`);
  for (let i = 0; i < COURSES.length; i++) console.log(`    ${String(KB(courses[i].length)).padStart(5)} KB  ${COURSES[i]}`);
}
